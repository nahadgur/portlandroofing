export function getNeighborhoodBySlug(slug:string) { return neighborhoods.find(n=>n.slug===slug) }
export function getStaticNeighborhoodPaths() { return neighborhoods.map(n=>({neighborhood:n.slug})) }
export function getNearbyNeighborhoods(slug:string,limit=6) {
  const current=getNeighborhoodBySlug(slug)
  return neighborhoods.filter(n=>n.slug!==slug).sort((a,b)=>Number(b.area===current?.area)-Number(a.area===current?.area)).slice(0,limit)
}
